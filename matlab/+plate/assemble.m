function system = assemble(mesh,material)
%ASSEMBLE Own sparse plate K/M and consistent element-pressure load operator.
% material.E [Pa], .nu [-], .rho [kg/m^3]. No membrane, contact, or curvature.
X=mesh.nodes; Q=mesh.quads; ne=size(Q,1); nd=3*size(X,1);
I=zeros(144,ne); J=I; VK=I; VM=I; IP=zeros(12,ne); VP=IP; area=zeros(ne,1);
for e=1:ne
    [ke,me,p,area(e)]=plate.mitc4(X(Q(e,:),:),mesh.thickness(e), ...
        material.E,material.nu,material.rho);
    dofs=reshape([3*Q(e,:)-2;3*Q(e,:)-1;3*Q(e,:)],[],1);
    [ii,jj]=ndgrid(dofs,dofs); I(:,e)=ii(:); J(:,e)=jj(:);
    VK(:,e)=ke(:); VM(:,e)=me(:); IP(:,e)=dofs; VP(:,e)=p;
end
system=struct('K',sparse(I(:),J(:),VK(:),nd,nd), ...
    'M',sparse(I(:),J(:),VM(:),nd,nd), ...
    'P',sparse(IP(:),repelem((1:ne)',12),VP(:),nd,ne), ...
    'mesh',mesh,'material',material,'area',area, ...
    'totalMass',sum(area.*mesh.thickness)*material.rho, ...
    'dofOrder','interleaved w [m], theta_x [rad], theta_y [rad]', ...
    'formulation','flat isotropic MITC4 plate, consistent mass including rotary inertia');
end
