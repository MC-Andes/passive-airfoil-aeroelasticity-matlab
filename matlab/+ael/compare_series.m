function report = compare_series(time,predicted,referenceTime,measured,scale)
%COMPARE_SERIES Compare synchronized observables, without extrapolation or shifts.
% Rows are observations; columns are times. Scale is explicit per observable
% (e.g. chord for displacement/chord), not inferred from measurement noise.
time=time(:)'; referenceTime=referenceTime(:)'; n=size(predicted,1);
assert(numel(time)>1 && all(isfinite(time)) && all(diff(time)>0) && ...
    numel(referenceTime)>1 && all(isfinite(referenceTime)) && all(diff(referenceTime)>0) && ...
    size(predicted,2)==numel(time) && isequal(size(measured),[n,numel(referenceTime)]) && ...
    all(isfinite(predicted(:))) && all(isfinite(measured(:))), ...
    'ael:Comparison','Require synchronized finite observable histories.');
assert(referenceTime(1)>=time(1) && referenceTime(end)<=time(end), ...
    'ael:ComparisonTime','Simulation must cover all reference sample times.');
if isscalar(scale), scale=repmat(scale,n,1); end
assert(numel(scale)==n && all(isfinite(scale(:)) & scale(:)>0), ...
    'ael:ComparisonScale','Supply a positive normalization scale per observable.');
aligned=interp1(time,predicted',referenceTime(:),'linear')'; error=aligned-measured;
rmse=sqrt(mean(error.^2,2)); bias=mean(error,2); peak=max(abs(error),[],2);
report=struct('rmse',rmse,'normalizedRMSE',rmse./scale(:),'bias',bias, ...
    'maxAbsoluteError',peak,'scale',scale(:),'time',referenceTime, ...
    'alignedPrediction',aligned,'error',error, ...
    'alignment','linear interpolation; no fitted time shift or extrapolation');
end
