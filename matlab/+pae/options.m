function settings = options(overrides)
%OPTIONS Shared solver tolerances; no optimization toolbox required.
if nargin<1, overrides=struct(); end
settings=struct('maxIterations',35,'relativeTolerance',1e-8,'absoluteTolerance',1e-9, ...
    'differenceStep',1e-6,'maxLineSearch',12,'errorOnFailure',true, ...
    'newmarkBeta',.25,'newmarkGamma',.5);
names=fieldnames(overrides);
for j=1:numel(names)
    assert(isfield(settings,names{j}),'pae:Options','Unknown setting %s.',names{j});
    settings.(names{j})=overrides.(names{j});
end
assert(settings.maxIterations>=1 && settings.maxIterations==fix(settings.maxIterations) && ...
    settings.maxLineSearch>=1 && settings.maxLineSearch==fix(settings.maxLineSearch) && ...
    settings.relativeTolerance>0 && settings.absoluteTolerance>0 && ...
    all(settings.differenceStep(:)>0) && settings.newmarkBeta>0 && settings.newmarkGamma>=.5, ...
    'pae:Options','Invalid solver settings.');
end
